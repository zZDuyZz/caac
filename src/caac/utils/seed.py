"""Centralised seeding -- every experiment reports over several seeds."""

from __future__ import annotations

import os
import random

import numpy as np

__all__ = ["set_seed"]


def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    try:
        import torch
        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(seed)
    except ImportError:
        pass
